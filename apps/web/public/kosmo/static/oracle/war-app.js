    NGA: "Nigeria", NIC: "Nicaragua", NPL: "Nepal", PAK: "Pakistan", PER: "Peru",
    PHL: "Philippines", PNG: "Papua New Guinea", RUS: "Russia", RWA: "Rwanda",
    SDN: "Sudan", SEN: "Senegal", SLE: "Sierra Leone", SLV: "El Salvador",
    SOM: "Somalia", SSD: "South Sudan", SYR: "Syria", TCD: "Chad", TGO: "Togo",
    THA: "Thailand", TJK: "Tajikistan", TTO: "Trinidad", TUN: "Tunisia",
