  /* The eight frames are five years apart, so stepping between them with a hard
     cut reads as a slideshow. Each transition is interpolated in screen space —
     position, radius and opacity all move — which is a statement about the
     drawing, not about the data: nothing is interpolated in the underlying
     numbers, and the year label never shows a year that has no frame. */
  function drawNow(si, dur, done) {
    if (!bubbles) return;
    cancel();
    var m = FR[si], lab = labelled(si);
    var items = [];

    isos.forEach(function (iso) {
      var e = bubbles.byIso[iso], r = m[iso], on = shown(r);
      if (on) e.row = r;                 /* keep the last row so a fading bubble still answers a hover */
      if (lab[iso]) e.t.textContent = NAMES[iso] || iso;
      items.push({
        e: e,
        x0: e.x, y0: e.y, r0: e.r, o0: e.o, l0: e.lo,
        x1: on ? sx(r[3]) : e.x,
        y1: on ? sy(r[2]) : e.y,
        r1: on ? sr(r[1]) : 0,
        o1: on ? 1 : 0,
        l1: lab[iso] ? 1 : 0
      });
    });

    var t0 = null, landed = false;

    function apply(k) {
      for (var i = 0; i < items.length; i++) {
        var it = items[i], e = it.e;
        e.x = it.x0 + (it.x1 - it.x0) * k;
        e.y = it.y0 + (it.y1 - it.y0) * k;
        e.r = it.r0 + (it.r1 - it.r0) * k;
        e.o = it.o0 + (it.o1 - it.o0) * k;
        e.lo = it.l0 + (it.l1 - it.l0) * k;

        if (e.r < 0.04 && e.o < 0.005) {
          if (e.c.getAttribute("r") !== "0") e.c.setAttribute("r", "0");
        } else {
          e.c.setAttribute("cx", e.x.toFixed(1));
          e.c.setAttribute("cy", e.y.toFixed(1));
          e.c.setAttribute("r", e.r.toFixed(2));
          e.c.setAttribute("fill-opacity", (0.26 * e.o).toFixed(3));
          e.c.setAttribute("stroke-opacity", (0.6 * e.o).toFixed(3));
        }

        if (e.lo > 0.004) {
          e.t.setAttribute("x", e.x.toFixed(1));
          e.t.setAttribute("y", (e.y - e.r - 5).toFixed(1));
          e.t.setAttribute("opacity", e.lo.toFixed(2));
        } else if (e.t.getAttribute("opacity") !== "0") {
          e.t.setAttribute("opacity", "0");
        }
      }

    }

    function land() {
      if (landed) return;
      landed = true;
      state.raf = null;
      clearTimeout(guard);
      if (done) done();
    }

    function step(now) {
      if (t0 == null) t0 = now;
      var p = Math.min(1, (now - t0) / dur);
      apply(easeInOut(p));
      if (p < 1) state.raf = requestAnimationFrame(step);
      else land();
    }

    /* rAF is tied to painting, and a frame that is never painted never fires it:
       an occluded window, a background tab, a starved compositor. Without this
       the chart would simply stay blank until something else forced a paint, so
       the transition also commits itself on a timer. */
    var guard = setTimeout(function () {
      if (landed) return;
      cancel();
      apply(1);
      land();
    }, dur + 160);

    if (dur > 0) state.raf = requestAnimationFrame(step);
    else { apply(1); land(); }
  }

  /* land on a frame with everything drawn at zero, in the right places: the
     next tween then grows the cloud in from nothing rather than flying 214
     bubbles across the plot from wherever the previous frame left them */
  function snap(si) {
    if (!bubbles) return;
    var m = FR[si];
    isos.forEach(function (iso) {
      var e = bubbles.byIso[iso], r = m[iso], on = shown(r);
      e.x = on ? sx(r[3]) : -30;
      e.y = on ? sy(r[2]) : -30;
      e.r = 0; e.o = 0; e.lo = 0;
      if (on) e.row = r;
      e.c.setAttribute("r", "0");
      e.c.setAttribute("cx", e.x.toFixed(1));
      e.c.setAttribute("cy", e.y.toFixed(1));
      e.c.setAttribute("fill-opacity", "0");
      e.c.setAttribute("stroke-opacity", "0");
      e.t.setAttribute("opacity", "0");
    });
  }

  function fadeOut(dur, done) {
    if (!bubbles) return;
    cancel();
    var items = isos.map(function (iso) {
      var e = bubbles.byIso[iso];
      return { e: e, o0: e.o, r0: e.r, l0: e.lo };
    });
    var t0 = null, landed = false;
    function apply(k) {
      for (var i = 0; i < items.length; i++) {
        var it = items[i], e = it.e;
        e.o = it.o0 * (1 - k);
        e.r = it.r0 * (1 - k);
        e.lo = it.l0 * (1 - k);
        e.c.setAttribute("r", e.r.toFixed(2));
        e.c.setAttribute("fill-opacity", (0.26 * e.o).toFixed(3));
        e.c.setAttribute("stroke-opacity", (0.6 * e.o).toFixed(3));
        e.t.setAttribute("opacity", e.lo.toFixed(2));
      }
    }

    function land() {
      if (landed) return;
      landed = true;
      state.raf = null;
      clearTimeout(guard);
      if (done) done();
    }

    function step(now) {
      if (t0 == null) t0 = now;
      var p = Math.min(1, (now - t0) / dur);
      apply(p * p);
      if (p < 1) state.raf = requestAnimationFrame(step);
      else land();
    }

    var guard = setTimeout(function () {
      if (landed) return;
      cancel();
      apply(1);
      land();
    }, dur + 160);

    state.raf = requestAnimationFrame(step);
  }

  function go(si, dur) {
    state.si = si;
    syncYear(si);
    drawNow(si, dur);
  }

