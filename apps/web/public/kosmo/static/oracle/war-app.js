  /* --------------------------------------------------------------- helpers */
  function el(t, cls, html) {
    var d = document.createElement(t);
    if (cls) d.className = cls;
    if (html != null) d.innerHTML = html;
    return d;
  }
  function clamp(x, a, b) { return x < a ? a : x > b ? b : x; }
  function int(n) { return Math.round(n).toLocaleString("en-US"); }
  function compact(n) {
    if (n == null || !isFinite(n)) return "–";
    if (Math.abs(n) >= 1e9) return (n / 1e9).toFixed(2) + "bn";
    if (Math.abs(n) >= 1e6) return (n / 1e6).toFixed(n >= 1e7 ? 0 : 1) + "m";
    if (Math.abs(n) >= 1e3) return (n / 1e3).toFixed(n >= 1e4 ? 0 : 1) + "k";
    return String(Math.round(n));
  }
  function usd(n) {
    if (n == null || !isFinite(n)) return "–";
    if (n >= 1e9) return "$" + (n / 1e9).toFixed(n >= 1e10 ? 0 : 1).replace(/\.0$/, "") + "bn";
    if (n >= 1e6) return "$" + (n / 1e6).toFixed(n >= 1e7 ? 0 : 1).replace(/\.0$/, "") + "M";
    if (n >= 1e3) return "$" + (n / 1e3).toFixed(n >= 1e4 ? 0 : 1).replace(/\.0$/, "") + "k";
    return "$" + Math.round(n);
  }
  var idxOf = {};
  W.years.forEach(function (y, i) { idxOf[y] = i; });

  function slice(years, from, to) {
    var out = [], i;
    for (i = 0; i < years.length; i++) if (years[i] >= from && years[i] <= to) out.push(years[i]);
    return out;
  }
  function pickFrom(arr, years, from, to) {
    var out = [];
    for (var i = 0; i < years.length; i++) if (years[i] >= from && years[i] <= to) out.push(arr[i]);
    return out;
  }

  function legendHTML(items) {
    return '<div class="legend">' + items.map(function (it) {
      return '<span><i style="background:' + it.color + (it.dash ? ";background-image:linear-gradient(90deg," + it.color + " 55%,transparent 55%);background-size:5px 3px" : "") + '"></i>' + it.name + "</span>";
    }).join("") + "</div>";
  }

  /* ============================================================ year charts
     One renderer for every "a value in every year" chart on the page: stacked
     areas, plain lines, a min/max ribbon and event marks. The hover model is
     built by hand rather than through HOV.linear because HOV.linear places its
     dots from the raw value, which is the wrong height inside a stack. */
  function chart(cfg) {
    var cw = cfg.w || 700, ch = cfg.h || 330;
    var m = { l: cfg.ml || 56, r: 16, t: 18, b: 30 };
    var iw = cw - m.l - m.r, ih = ch - m.t - m.b;
    var yrs = cfg.years, n = yrs.length, x0 = yrs[0], x1 = yrs[n - 1];
    var ax = cfg.left;

    function X(v) { return n < 2 ? m.l : m.l + (v - x0) / (x1 - x0) * iw; }
    function Y(v) {
      if (ax.log) {
        var lo = Math.log10(ax.min), hi = Math.log10(ax.max);
        return m.t + (1 - (Math.log10(clamp(v, ax.min, ax.max)) - lo) / (hi - lo)) * ih;
      }
      return m.t + (1 - (clamp(v, ax.min, ax.max) - ax.min) / (ax.max - ax.min)) * ih;
    }

    var s = '<svg viewBox="0 0 ' + cw + " " + ch + '" role="img" aria-label="' + (cfg.aria || "") + '">';

    (cfg.yTicks || []).forEach(function (v) {
      var y = Y(v);
      s += '<line x1="' + m.l + '" x2="' + (cw - m.r) + '" y1="' + y.toFixed(1) + '" y2="' + y.toFixed(1) +
        '" stroke="' + C.line + '" stroke-dasharray="2 4"/>';
      s += '<text x="' + (m.l - 7) + '" y="' + (y + 3.5).toFixed(1) + '" text-anchor="end" fill="' + C.dim2 +
        '" font-size="9" font-family="ui-monospace,monospace">' + ax.fmt(v) + "</text>";
    });

    (cfg.xTicks || []).forEach(function (yr) {
      if (yr < x0 || yr > x1) return;
      s += '<text x="' + X(yr).toFixed(1) + '" y="' + (ch - 9) + '" text-anchor="middle" fill="' + C.dim2 +
        '" font-size="9" font-family="ui-monospace,monospace">' + yr + "</text>";
    });

    /* ribbon first, so it sits behind the stack it belongs to */
    if (cfg.band) {
      var up = "", dn = "", started = false;
      for (var i = 0; i < n; i++) {
        var hi = cfg.band.hi[i], lo = cfg.band.lo[i];
        if (hi == null || lo == null) { started = false; continue; }
        up += (started ? "L" : "M") + X(yrs[i]).toFixed(1) + " " + Y(hi).toFixed(1);
        started = true;
      }
      for (var j = n - 1; j >= 0; j--) {
        var lo2 = cfg.band.lo[j], hi2 = cfg.band.hi[j];
        if (hi2 == null || lo2 == null) continue;
        dn += "L" + X(yrs[j]).toFixed(1) + " " + Y(lo2).toFixed(1);
      }
      s += '<path d="' + up + dn + 'Z" fill="' + (cfg.band.color || C.mint) + '" opacity="' + (cfg.band.opacity || 0.1) + '"/>';
    }

    var cum = new Array(n).fill(0);
    (cfg.stack || []).forEach(function (se) {
      var top = [], base = [], k;
      for (k = 0; k < n; k++) {
        var v = se.data[k];
        if (v == null || !isFinite(v)) v = 0;
        base.push(cum[k]);
        top.push(cum[k] + v);
        cum[k] = cum[k] + v;
      }
      var d = "";
      for (k = 0; k < n; k++) d += (k ? "L" : "M") + X(yrs[k]).toFixed(1) + " " + Y(top[k]).toFixed(1);
      for (k = n - 1; k >= 0; k--) d += "L" + X(yrs[k]).toFixed(1) + " " + Y(base[k]).toFixed(1);
      s += '<path d="' + d + 'Z" fill="' + se.color + '" opacity="' + (se.opacity || 0.42) + '"/>';
      /* a hairline along the top of each band, so thin slivers still read */
      var tl = "";
      for (k = 0; k < n; k++) tl += (k ? "L" : "M") + X(yrs[k]).toFixed(1) + " " + Y(top[k]).toFixed(1);
      s += '<path d="' + tl + '" fill="none" stroke="' + se.color + '" stroke-width="1.1" opacity="0.9"/>';
    });

    (cfg.line || []).forEach(function (se) {
      var d = "", started = false;
      for (var k = 0; k < n; k++) {
        var v = se.data[k];
        if (v == null || !isFinite(v)) { started = false; continue; }
        d += (started ? "L" : "M") + X(yrs[k]).toFixed(1) + " " + Y(v).toFixed(1);
        started = true;
      }
      s += '<path d="' + d + '" fill="none" stroke="' + se.color + '" stroke-width="' + (se.width || 2) +
        '" stroke-linejoin="round" stroke-linecap="round"' + (se.dash ? ' stroke-dasharray="4 3"' : "") +
        (se.opacity ? ' opacity="' + se.opacity + '"' : "") + "/>";
    });

    (cfg.marks || []).forEach(function (mk) {
      var x = X(mk.year);
      s += '<line x1="' + x.toFixed(1) + '" x2="' + x.toFixed(1) + '" y1="' + m.t + '" y2="' + (m.t + ih) +
        '" stroke="' + (mk.color || C.dim2) + '" stroke-dasharray="3 4" opacity="0.75"/>';
      /* a mark in the last fifth of the axis has no room for a label on its
         right, so it hangs the label to the left of the line instead */
      var flip = x > m.l + iw * 0.82;
      s += '<text x="' + (flip ? x - 4 : x + 4).toFixed(1) + '" text-anchor="' + (flip ? "end" : "start") +
        '" y="' + (m.t + 12 + (mk.drop || 0)) + '" fill="' + C.dim +
        '" font-size="9.5" font-family="ui-monospace,monospace">' + mk.label + "</text>";
    });

    s += "</svg>";

    var model = {
      W: cw, H: ch, top: m.t, bottom: m.t + ih,
      xOf: function (i) { return X(yrs[i]); },
      xIndex: function (vx) {
        var t = (vx - m.l) / iw;
        return clamp(Math.round(t * (n - 1)), 0, n - 1);
      },
      label: cfg.label || function (i) { return String(yrs[i]); },
      rows: function (i) {
        var rows = [];
        if (cfg.band) {
          var hi = cfg.band.hi[i], lo = cfg.band.lo[i];
          if (hi != null && lo != null) {
            rows.push({
              name: (cfg.band.name || "published range"), color: cfg.band.color || C.mint,
              text: int(lo) + " – " + int(hi)
            });
          }
        }
        (cfg.stack || []).concat(cfg.line || []).forEach(function (se) {
          var v = se.data[i];
          if (v == null || !isFinite(v)) return;
          rows.push({ name: se.name, color: se.color, dash: !!se.dash, text: (se.fmt || cfg.fmt || int)(v) });
        });
        return rows;
      }
    };
    return { html: s, model: model };
  }

  function mount(id, cfg) {
    var host = document.getElementById(id);
    if (!host) return null;
    var out = chart(cfg);
    host.innerHTML = out.html + (cfg.legend ? legendHTML(cfg.legend) : "");
    if (window.HOV) HOV.bind(host, out.model);
    return host;
  }

