  function start() {
    if (state.playing) return;
    state.playing = true;
    syncPlay();
    tick();
  }

  /* A timeout chain rather than an interval: a tween can run long on a slow
     frame, and an interval would queue steps behind it and then rush to catch
     up, which is the stutter this replaces. */
  function tick() {
    if (!state.playing) return;
    var n = W.scatter.length;

    if (state.si >= n - 1) {
      /* hold the last frame, then fade and restart. Tweening 2023 straight back
         to 1990 would read as a glitch, because it is not time passing. */
      state.timer = setTimeout(function () {
        if (!state.playing) return;
        fadeOut(280, function () {
          snap(0);
          state.si = 0;
          syncYear(0);
          drawNow(0, 560);
          if (state.playing) state.timer = setTimeout(tick, 1240);
        });
      }, 700);
      return;
    }

    go(state.si + 1, 760);
    state.timer = setTimeout(tick, 1180);
  }

  function stop() {
    state.playing = false;
    clearTimeout(state.timer);
    state.timer = null;
    syncPlay();
  }

