/* ============================================================================
   fuels.js — energy, climate and population, 1800 to the far future.

   History is measured (fuels-data.js, generated by ingest-energy.mjs).
   Everything after 2025 is computed here, and the computation has three parts
   that are deliberately separable so each can be argued with on its own:

     1. ENERGY    a cost-competition model. Every fuel has a levelised cost; cost
                  relative to the cheapest fuel sets market share; shares move
                  toward that target with a per-fuel time constant. Fossil costs
                  rise with depletion (cumulative extraction / ultimately
                  recoverable resources) and with a carbon price. Clean costs fall
                  on a learning curve but rise with penetration, because storage
                  and grid integration are real costs that scale with share.

     2. CARBON    emissions feed a four-box impulse response (Joos et al. 2013),
                  the same reduced-form IPCC AR5 uses. A tonne emitted today is
                  ~22% still airborne in 10,000 years, which is why the far-future
                  charts do not return to baseline after emissions stop.

     3. CLIMATE   a two-layer energy balance. Forcing from CO2/CH4/N2O/aerosols,
                  an upper layer with a small heat capacity and a deep layer with a
                  huge one. The split is what produces committed warming: the
                  surface tracks forcing, but the deep ocean takes centuries to
                  catch up, so temperature keeps rising after emissions end.

   The only exogenous futures are population (UN to 2100, then a lever) and energy
   per capita (a saturating path to a lever). Everything else follows from prices,
   physics and the carbon budget.
   ============================================================================ */
