/** The pin for `id` with its re-cut applied: the object the checks compare the measured ship against. */
export function pinned(pin, id) {
  const r = RECUTS[id];
  if (!r) return pin;
  const out = JSON.parse(JSON.stringify(pin));
  for (const [path, v] of Object.entries(r.fields)) {
    const keys = path.split('.');
    let o = out;
    for (const k of keys.slice(0, -1)) o = o[k];
    o[keys[keys.length - 1]] = v.now;
  }
  return out;
}

