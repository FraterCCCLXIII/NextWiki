#!/usr/bin/env node
/* Builds the SpaceRadio, Modern Telepathy and TempleOS parts of the logo reel (apps/web/public/logo-reel/*-reel.js).
   The Kosmographica half comes from the loader in apps/web/public/logo-loader.
   Change SPACERADIO_PICKS (sheet numbers) to change the reel, and <brand>/hidden.json to keep a logo in the sheet
   but out of the reel while it is being fixed, then run:  node tools/build-logo-reel.mjs */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srDir = join(root, "spaceradio-logos");
const tosDir = join(root, "templeos-logos");
const out = join(root, "apps/web/public/logo-reel");

/* Sheet numbers of the SpaceRadio logos in the reel. Every Modern Telepathy logo is included. */
const SPACERADIO_PICKS = [14, 19, 26, 42, 46, 47, 57, 59, 61, 70, 89, 125, 128, 129, 142, 146, 156];

/* Sheet numbers held back from the reel while their vectors are still being fixed. They stay in the
   brand's sheet.html and traced data, so adding a number only hides that logo and removing it brings
   the logo back. One JSON list per brand: <brand>/hidden.json, e.g. [61, 68]. */
function hiddenIn(dir) {
  const file = join(root, dir, "hidden.json");
  if (!existsSync(file)) return new Set();
  const list = JSON.parse(readFileSync(file, "utf8"));
  return new Set((Array.isArray(list) ? list : []).map(String));
}
const withoutHidden = (logos, dir) => {
  const hide = hiddenIn(dir);
  return Object.fromEntries(Object.entries(logos).filter(([n]) => !hide.has(n)));
};

const tpl = readFileSync(join(srDir, "sheet.template.html"), "utf8");
const start = tpl.indexOf("const NS=");
const end = tpl.indexOf("/* ---- sound:");
if (start < 0 || end < 0) throw new Error("reveal code markers not found in sheet.template.html");
const reveals = tpl.slice(start, end);

function logosIn(dir) {
  const m = readFileSync(join(root, dir, "sheet.html"), "utf8").match(/const LOGOS=(\{.*\});/);
  if (!m) throw new Error(`LOGOS not found in ${dir}/sheet.html`);
  return JSON.parse(m[1]);
}
const pickFrom = (all, numbers) => Object.fromEntries(numbers.map((n) => {
  if (!all[n]) throw new Error(`no logo ${n}`);
  return [n, all[n]];
}));

mkdirSync(out, { recursive: true });
const metaFrom = (dir, numbers) => {
  const logos = JSON.parse(readFileSync(join(root, dir, "sheet-numbers.json"), "utf8")).logos;
  return Object.fromEntries(numbers.map((n) => { const m = logos[n] || {}; return [n, { traceMatch: m.iou, mode: m.mode, source: m.sheetTitle || null, font: m.wordmarkFont ? `${m.wordmarkFont.file.split(/[-.]/)[0]} ${m.wordmarkFont.wght}${m.wordmarkFont.wdth ? ` width ${m.wordmarkFont.wdth}` : ""}` : null }]; }));
};
const emit = (file, picks, globalName, prefix, meta, opts = {}) => writeFileSync(join(out, file), `/* Generated by tools/build-logo-reel.mjs. Do not edit. */
(function(){
const PICKS=${JSON.stringify(picks)};
const CURVE_FILL=${!!opts.curveFill};
${reveals}
const rgb=h=>{const m=/^#?([\\da-f]{2})([\\da-f]{2})([\\da-f]{2})/i.exec(h);return m?[parseInt(m[1],16),parseInt(m[2],16),parseInt(m[3],16)]:null};
const rel=c=>{const f=c.map(v=>{v/=255;return v<=.03928?v/12.92:Math.pow((v+.055)/1.055,2.4)});return .2126*f[0]+.7152*f[1]+.0722*f[2]};
/* anything too close to the background to read flips to white on dark, or near-black on light */
function recolour(svg,bg){
  if(svg.hasAttribute('data-panel'))return;
  const b=rgb(bg),bl=rel(b),dark=bl<.18;
  svg.querySelectorAll('[fill]').forEach(e=>{const c=rgb(e.getAttribute('fill'));if(!c)return;
    const chroma=Math.max(...c)-Math.min(...c),l=(.2126*c[0]+.7152*c[1]+.0722*c[2])/255,fl=rel(c),contrast=(Math.max(fl,bl)+.05)/(Math.min(fl,bl)+.05);
    if(dark&&((l<.16&&chroma<70)||contrast<1.3))e.setAttribute('fill','#ffffff');
    else if(!dark&&contrast<1.25)e.setAttribute('fill','#111116');});
}
let uid=0;
function mount(el,n,o){
  const L=PICKS[n],fid='${prefix}crt'+(++uid),root=document.createElement('div');root.style.cssText='width:100%;height:100%;--paper:'+o.bg;el.appendChild(root);
  const dark=rel(rgb(o.bg))<.18;
  let setLv=null;
  const paint=v=>{const g=root.querySelector('g.sr-fx'),lv=window.KosmoLogoLoader.crtLevels(v);if(!g)return;if(lv.blur||lv.bloom){setLv(lv);g.setAttribute('filter','url(#'+fid+')')}else g.removeAttribute('filter')};
  const draw=()=>{root.innerHTML=markup(L);const svg=root.firstChild;svg.querySelectorAll('.pp').forEach(p=>p.setAttribute('fill',o.bg));recolour(svg,o.bg);
    const fx=svgEl('g',{class:'sr-fx'});[...svg.children].forEach(c=>{if(c.tagName!=='defs')fx.appendChild(c)});svg.appendChild(fx);setLv=window.KosmoLogoLoader.addCrtFilter(svg,fid,dark?'dark':'light');paint(o.crt);return svg};
  TS=1;anims=[];let svg=draw();plan(collect(svg,L),L,n);
  const e=Math.max(...anims.map(a=>{const t=a.effect.getTiming();return t.delay+t.duration}));
  if(e>3000){anims.forEach(a=>a.cancel());TS=3000/e;anims=[];svg=draw();plan(collect(svg,L),L,n);TS=1}
  const mine=anims;anims=[];
  return {destroy(){mine.forEach(a=>a.cancel());root.remove()},setCrt(v){paint(v)}};
}
/* a dark background chosen from this logo's own colors */
function backdrop(n){const fills=[];PICKS[n].p.forEach(p=>{if(p.k==='p')return;if(p.L)p.L.forEach(l=>fills.push({hex:l[0],weight:(p.a||1)/p.L.length}));else if(p.f)fills.push({hex:p.f,weight:p.a||1})});return window.KosmoLogoLoader.pickBackdrop(fills,'${prefix}'+n)}
window.${globalName}={ids:Object.keys(PICKS).map(Number),mount,backdrop,meta:${JSON.stringify(meta)}};
})();
`);
const spaceradio = withoutHidden(pickFrom(logosIn("spaceradio-logos"), SPACERADIO_PICKS), "spaceradio-logos");
emit("spaceradio-reel.js", spaceradio, "SpaceRadioReel", "sr", metaFrom("spaceradio-logos", Object.keys(spaceradio)));
const telepathy = withoutHidden(logosIn("modern-telepathy-logos"), "modern-telepathy-logos");
emit("modern-telepathy-reel.js", telepathy, "ModernTelepathyReel", "mt", metaFrom("modern-telepathy-logos", Object.keys(telepathy)));
/* Traced brands: build.py in each folder writes logos.json from its sheet, so it goes straight in.
   Until that has run the brand is left out rather than breaking the reel. */
const emitTraced = (dir, file, globalName, prefix, source, opts) => {
  const data = join(root, dir, "logos.json");
  if (!existsSync(data)) return null;
  const logos = withoutHidden(JSON.parse(readFileSync(data, "utf8")), dir);
  const numbers = JSON.parse(readFileSync(join(root, dir, "sheet-numbers.json"), "utf8")).logos;
  const meta = Object.fromEntries(Object.keys(logos).map((n) => {
    const m = numbers[n] || {};
    return [n, { traceMatch: m.iou ?? null, mode: m.mode || null, source, font: null }];
  }));
  emit(file, logos, globalName, prefix, meta, opts);
  return Object.keys(logos).length;
};
const templeosN = emitTraced("templeos-logos", "templeos-reel.js", "TempleOSReel", "to", "TempleOS sheet");
const kosmosN = emitTraced("kosmos-logos", "kosmos-reel.js", "KosmosReel", "ko", "KOSMOS sheet", { curveFill: true });
for (const [name, n, dir] of [["TempleOS", templeosN, "templeos-logos"], ["Kosmos", kosmosN, "kosmos-logos"]]) {
  if (n === null) console.log(`${name}: no ${dir}/logos.json yet, run ${dir}/build.sh once refs/ has the sheet`);
}
const held = [["SpaceRadio", "spaceradio-logos", SPACERADIO_PICKS.length, spaceradio], ["Modern Telepathy", "modern-telepathy-logos", Object.keys(logosIn("modern-telepathy-logos")).length, telepathy], ["TempleOS", "templeos-logos", null, null], ["Kosmos", "kosmos-logos", null, null]]
  .map(([name, dir, total, shown]) => ({ name, n: hiddenIn(dir).size, total, shown }))
  .filter((b) => b.n > 0)
  .map((b) => `${b.name} ${b.n}${b.total ? ` of ${b.total}` : ""}`);
console.log(`${Object.keys(spaceradio).length} SpaceRadio, ${Object.keys(telepathy).length} Modern Telepathy, ${templeosN ?? 0} TempleOS and ${kosmosN ?? 0} Kosmos logos in the reel`);
if (held.length) console.log(`held back for fixes: ${held.join(", ")}`);
