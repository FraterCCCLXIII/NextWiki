/**
 * Checks the source ledger and the gap map, prints coverage, and writes the table.
 *
 *   pnpm --filter @repo/db db:university:sources            check and print coverage
 *   pnpm --filter @repo/db db:university:sources --write    also rewrite docs/university-sources.md
 *
 * Exits 1 on any ledger or map error. Open gaps (modules with no source yet) are not errors.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { loadCurriculum } from "./content.js";
import { LICENSES } from "./licenses.js";
import { gapReport, validateLedger, validateMap, type Ledger, type MapEntry, type SourceMap } from "./sources.js";
import { readLedger, readSourceMap } from "./sources-io.js";
import { universityDir } from "./paths.js";

const esc = (s: string) => s.replace(/\|/g, "\\|");

export function renderTable(
  stages: Awaited<ReturnType<typeof loadCurriculum>>["stages"],
  ledger: Ledger,
  map: SourceMap,
): string {
  const out: string[] = [
    "# University: sources for every module",
    "",
    "Generated by `pnpm --filter @repo/db db:university:sources --write`. Do not edit by hand:",
    "edit `sources.json` (the ledger) and `source-map.json` (the gap map) and regenerate.",
    "",
    "The portal is free and non-commercial, so NonCommercial sources may be adapted; ND and",
    "no-licence sources are link-only. **Mode**: link = point learners at it; adapt = lessons may be",
    "written from it; ingest = a copy is stored in the repo. **Fit**: full = covers the module;",
    "partial = covers part of it.",
    "",
  ];
  const total = stages.flatMap((s) => s.programmes.flatMap((p) => p.modules)).length;
  const covered = Object.keys(map.modules).length;
  out.push(`**${covered} of ${total} modules have at least one source. ${total - covered} are open gaps.**`, "");

  for (const stage of stages) {
    out.push(`## ${stage.name}`, "");
    for (const prog of stage.programmes) {
      out.push(`### ${prog.name}`, "", "| Module | Lessons | Source | Licence | Fit | Mode |", "|---|---|---|---|---|---|");
      for (const mod of prog.modules) {
        const entries: MapEntry[] = map.modules[mod.id] ?? [];
        if (!entries.length) {
          out.push(`| ${esc(mod.name)} (\`${mod.id}\`) | ${mod.lessons.length} | **open gap** | | | |`);
          continue;
        }
        entries.forEach((e, i) => {
          const s = ledger.sources[e.source]!;
          const link = `[${esc(e.locator)}](${e.url ?? s.url})`;
          const lic = LICENSES[s.license]?.name ?? s.license;
          out.push(
            `| ${i === 0 ? `${esc(mod.name)} (\`${mod.id}\`)` : ""} | ${i === 0 ? mod.lessons.length : ""} | ${link} — ${esc(s.title)} | ${lic} | ${e.fit} | ${e.mode} |`,
          );
        });
      }
      out.push("");
    }
  }

  out.push("## Ledger", "", "| Id | Source | Licence | Checked | Mode | AI use | Ingested |", "|---|---|---|---|---|---|---|");
  for (const s of Object.values(ledger.sources).sort((a, b) => a.id.localeCompare(b.id))) {
    const ing = s.ingest ? `${(s.ingest.bytes / 1e6).toFixed(1)} MB at \`${s.ingest.path}\`` : "";
    out.push(`| \`${s.id}\` | [${esc(s.title)}](${s.url}) — ${esc(s.publisher)} | ${LICENSES[s.license]?.name ?? s.license} | ${s.licenseCheckedAt} | ${s.mode} | ${s.aiUse === "restricted" ? `[restricted](${s.aiUseUrl})` : "ok"} | ${ing} |`);
  }
  out.push("");
  return out.join("\n");
}

async function main() {
  const cur = await loadCurriculum();
  if (cur.fatal.length) {
    for (const f of cur.fatal) console.error(`FATAL ${f}`);
    process.exit(1);
  }
  const ledger = await readLedger();
  const map = await readSourceMap();
  const ids = cur.stages.flatMap((s) => s.programmes.flatMap((p) => p.modules.map((m) => m.id)));

  const problems = [...validateLedger(ledger), ...validateMap(map, ledger, new Set(ids))];
  for (const p of problems) console.error(`error: ${p}`);

  const r = gapReport(map, ids);
  console.log(`Sources in ledger: ${Object.keys(ledger.sources).length}`);
  console.log(`Modules: ${r.modules}  with a source: ${r.covered}  with a full-fit source: ${r.full}  open gaps: ${r.open.length}`);
  const ingested = Object.values(ledger.sources).filter((s) => s.ingest);
  const bytes = ingested.reduce((n, s) => n + (s.ingest?.bytes ?? 0), 0);
  console.log(`Ingested: ${ingested.length} source(s), ${(bytes / 1e6).toFixed(1)} MB`);

  if (process.argv.includes("--write")) {
    const file = path.join(universityDir(), "..", "..", "..", "..", "..", "..", "docs", "university-sources.md");
    await writeFile(file, renderTable(cur.stages, ledger, map));
    console.log(`Wrote ${path.relative(process.cwd(), file)}`);
  }
  if (problems.length) {
    console.error(`\n${problems.length} problem(s).`);
    process.exit(1);
  }
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
